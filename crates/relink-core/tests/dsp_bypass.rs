use relink_core::*;

fn configured() -> DspConfig {
    DspConfig {
        high_pass: Some(HighPassConfig { cutoff_hz: 137.0 }),
        gate: Some(GateConfig {
            threshold_db: -37.0,
            attack_ms: 3.0,
            hold_ms: 83.0,
            release_ms: 317.0,
        }),
        compressor: Some(CompressorConfig {
            threshold_db: -27.0,
            ratio: 7.5,
            attack_ms: 1.3,
            release_ms: 213.0,
            makeup_gain_db: 5.0,
        }),
        limiter: Some(LimiterConfig {
            ceiling_db: -4.0,
            release_ms: 71.0,
        }),
        bypass: DspBypass::default(),
    }
}
fn fixture() -> Session {
    let mut session = Session::new("Generated bypass persistence controls", 48000);
    let mut input = Input::new(
        "Generated source",
        InputKind::Hardware {
            device_id: "in-memory-only".into(),
        },
    );
    input.dsp = configured();
    let input = session.add_input(input).unwrap();
    let mut bus = Bus::new("Mix");
    bus.dsp = configured();
    let bus = session.add_bus(bus).unwrap();
    session.add_send(Send::new(input, bus)).unwrap();
    session
}
fn bank(session: &Session) -> PreparedControls {
    PreparedControls::compile(session, 1024 * 1024).unwrap()
}
fn render(mixer: &mut CompiledMixer, session: &Session, source: &[f32]) -> Vec<f32> {
    let mut left = vec![0.0; source.len()];
    let mut right = vec![0.0; source.len()];
    mixer
        .render(
            &[StereoInput {
                id: session.inputs[0].id,
                left: source,
                right: source,
            }],
            &mut [StereoOutput {
                id: session.buses[0].id,
                left: &mut left,
                right: &mut right,
            }],
            source.len(),
        )
        .unwrap();
    left
}

#[test]
fn legacy_sessions_without_bypass_keep_parameters_coefficients_and_audio_identical() {
    let session = fixture();
    let mut legacy = serde_json::to_value(&session).unwrap();
    for group in ["inputs", "buses"] {
        for channel in legacy[group].as_array_mut().unwrap() {
            channel["dsp"].as_object_mut().unwrap().remove("bypass");
        }
    }
    let restored = Session::from_json(&legacy.to_string()).unwrap();
    assert_eq!(restored, session);
    assert_eq!(bank(&restored), bank(&session));
    let mut original = CompiledMixer::compile(&session, ResourceBudget::default()).unwrap();
    let mut restored_mixer = CompiledMixer::compile(&restored, ResourceBudget::default()).unwrap();
    let source: Vec<_> = (0..1024).map(|n| (n as f32 * 0.13).sin() * 0.7).collect();
    for _ in 0..4 {
        assert_eq!(
            render(&mut original, &session, &source),
            render(&mut restored_mixer, &restored, &source)
        );
    }
}

#[test]
fn bypass_round_trip_and_partial_flags_preserve_every_custom_parameter() {
    let mut session = fixture();
    session.inputs[0].dsp.bypass = DspBypass {
        high_pass: true,
        compressor: true,
        ..Default::default()
    };
    session.buses[0].dsp.bypass = DspBypass {
        gate: true,
        limiter: true,
        ..Default::default()
    };
    let restored = Session::from_json(&session.to_json().unwrap()).unwrap();
    assert_eq!(restored, session);
    let mut partial = serde_json::to_value(&session).unwrap();
    partial["inputs"][0]["dsp"]["bypass"] = serde_json::json!({"gate": true});
    let restored = Session::from_json(&partial.to_string()).unwrap();
    assert_eq!(
        restored.inputs[0].dsp.bypass,
        DspBypass {
            gate: true,
            ..Default::default()
        }
    );
    let mut parameters = restored.inputs[0].dsp.clone();
    parameters.bypass = DspBypass::default();
    assert_eq!(parameters, configured());
    partial["inputs"][0]["dsp"]["bypass"]["unknown_stage"] = serde_json::json!(true);
    assert!(Session::from_json(&partial.to_string()).is_err());
}

#[test]
fn prepared_bypass_changes_only_enabled_mask_and_never_discards_coefficients() {
    let mut session = fixture();
    let original = bank(&session);
    session.inputs[0].dsp.bypass = DspBypass {
        high_pass: true,
        gate: true,
        compressor: true,
        limiter: true,
    };
    session.buses[0].dsp.bypass = DspBypass {
        compressor: true,
        ..Default::default()
    };
    let bypassed = bank(&session);
    for (before, after, expected_mask) in [
        (original.input_dsp[0], bypassed.input_dsp[0], 0),
        (original.bus_dsp[0], bypassed.bus_dsp[0], 0b1011),
    ] {
        let before = before.to_words();
        let after = after.to_words();
        assert_eq!(after[1], expected_mask);
        assert_eq!(before[0], after[0]);
        assert_eq!(before[2..], after[2..]);
        assert!(PreparedDsp::from_words(after).is_ok());
    }
    session.inputs[0].dsp.bypass = DspBypass::default();
    session.buses[0].dsp.bypass = DspBypass::default();
    assert_eq!(bank(&session), original);
}

#[test]
fn bypass_does_not_allow_invalid_configured_parameters_into_session_or_bank() {
    for stage in 0..4 {
        let mut session = fixture();
        session.inputs[0].dsp.bypass = DspBypass {
            high_pass: true,
            gate: true,
            compressor: true,
            limiter: true,
        };
        match stage {
            0 => session.inputs[0].dsp.high_pass.as_mut().unwrap().cutoff_hz = 24000.0,
            1 => session.inputs[0].dsp.gate.as_mut().unwrap().threshold_db = 1.0,
            2 => session.inputs[0].dsp.compressor.as_mut().unwrap().ratio = 0.0,
            _ => session.inputs[0].dsp.limiter.as_mut().unwrap().ceiling_db = 1.0,
        }
        assert!(session.validate().is_err());
        assert!(PreparedControls::compile(&session, 1024 * 1024).is_err());
        assert!(CompiledMixer::compile(&session, ResourceBudget::default()).is_err());
        // JSON input must not escape validation merely because the stage is bypassed.
        assert!(Session::from_json(&serde_json::to_string(&session).unwrap()).is_err());
    }
}

#[test]
fn each_configured_stage_can_audition_dry_and_restore_its_custom_processing() {
    for stage in 0..4 {
        let mut session = fixture();
        session.inputs[0].dsp = DspConfig::default();
        session.buses[0].dsp = DspConfig::default();
        let level = match stage {
            0 => {
                session.inputs[0].dsp.high_pass = Some(HighPassConfig { cutoff_hz: 333.0 });
                0.8
            }
            1 => {
                session.inputs[0].dsp.gate = Some(GateConfig {
                    threshold_db: -6.0,
                    attack_ms: 0.01,
                    ..Default::default()
                });
                0.2
            }
            2 => {
                session.inputs[0].dsp.compressor = Some(CompressorConfig {
                    threshold_db: -30.0,
                    ratio: 8.0,
                    attack_ms: 0.01,
                    makeup_gain_db: 6.0,
                    ..Default::default()
                });
                0.8
            }
            _ => {
                session.inputs[0].dsp.limiter = Some(LimiterConfig {
                    ceiling_db: -12.0,
                    release_ms: 73.0,
                });
                0.8
            }
        };
        let parameters = session.inputs[0].dsp.clone();
        let active_bank = bank(&session);
        let mut mixer = CompiledMixer::compile(&session, ResourceBudget::default()).unwrap();
        let source = vec![level; 2048];
        let active = render(&mut mixer, &session, &source);
        let processed = active[active.len() - 1];
        assert!((processed - level).abs() > 0.1);
        match stage {
            0 => session.inputs[0].dsp.bypass.high_pass = true,
            1 => session.inputs[0].dsp.bypass.gate = true,
            2 => session.inputs[0].dsp.bypass.compressor = true,
            _ => session.inputs[0].dsp.bypass.limiter = true,
        }
        mixer.apply_controls(&bank(&session)).unwrap();
        let dry = render(&mut mixer, &session, &source);
        assert!(dry[239..].iter().all(|sample| *sample == level));
        // Reopening the saved bypassed state also starts exactly dry.
        let saved = Session::from_json(&session.to_json().unwrap()).unwrap();
        let mut reopened = CompiledMixer::compile(&saved, ResourceBudget::default()).unwrap();
        assert!(render(&mut reopened, &saved, &source)
            .iter()
            .all(|sample| *sample == level));
        session.inputs[0].dsp.bypass = DspBypass::default();
        assert_eq!(session.inputs[0].dsp, parameters);
        assert_eq!(bank(&session), active_bank);
        mixer.apply_controls(&active_bank).unwrap();
        let restored = render(&mut mixer, &session, &source);
        assert!((restored[restored.len() - 1] - processed).abs() < 1.0e-6);
    }
}
